






local gen = require("santoku.gen")
local vec = require("santoku.vector")

describe("santoku.gen", function ()

























































































































































































































































































































  describe("map", function ()

    it("maps over a generator", function ()

      local i = 0
      local gen = gen.gen(function ()
        i = i + 1
        return true, i
      end):map(function (a)
        return a * 2
      end)

      local ok, v

      ok, v = gen()

      assert(ok)
      assert.equals(2, v)

      ok, v = gen()

      assert(ok)
      assert.equals(4, v)

    end)

  end)

  describe("reduce", function ()

    it("reduces a generator", function ()
      local i = 0
      local gen = gen.gen(function ()
        i = i + 1
        if i > 3 then
          return
        else
          return true, i
        end
      end)
      local t = gen:reduce(function (a, n, i)
        return a + n
      end)
      assert.equals(t, 6)
    end)

    it("returns the initial value for a empty generator", function ()
      local gen = gen.gen(function () return end)
      local v = gen:reduce(function () end, 10)
      assert.equals(10, v)
    end)

  end)





























































































































































































































































































































end)
