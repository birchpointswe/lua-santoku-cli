






local gen = require("santoku.gen")
local vec = require("santoku.vector")

describe("santoku.gen", function ()

  describe("gen", function ()

    it("should allow for cps", function ()

      local gen = gen.gen(function (each, ret)
        each(function ()
          each(function ()
            each(ret, 3)
          end, 2)
        end, 1)
      end)

      local vals = gen:vec()
      assert(vals[1] == 1)
      assert(vals[2] == 2)
      assert(vals[3] == 3)

    end)

  end)


































































































































































































































































































































































































































































































































































end)
