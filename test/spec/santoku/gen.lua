






local gen = require("santoku.gen")
local vec = require("santoku.vector")

describe("santoku.gen", function ()

  describe("gen", function ()

    it("should allow for cps", function ()

      local gen = gen.gen(function (ret)
        ret(1)
        ret(2)
        ret(3)
      end)

      local vals = gen:vec()
      assert(vals[1] == 1)
      assert(vals[2] == 2)
      assert(vals[3] == 3)

    end)

  end)

  describe("map", function ()

    it("maps over a generator", function ()

      local gen = gen.gen(function (ret)
        ret(1)
        ret(2)
      end):map(function (a)
        return a * 2
      end)

      local vals = gen:vec()
      assert(vals[1] == 2)
      assert(vals[2] == 4)

    end)

  end)
































































































































































































































































































































































































































































































































end)
